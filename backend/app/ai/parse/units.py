"""Единицы измерения: варианты написания → каноническое обозначение.

Приведение делает код, а не модель. Незнакомая единица не угадывается,
строка уходит на проверку (ПР-9).
"""

import re

_VARIANTS: dict[str, list[str]] = {
    "шт": ["шт", "штука", "штуки", "штук", "штучка", "pcs", "pc"],
    "упак": ["упак", "уп", "упаковка", "упаковки", "упаковок", "пачка", "пачки", "пачек"],
    "компл": ["компл", "комплект", "комплекта", "комплектов", "к-т", "кт"],
    "пара": ["пара", "пары", "пар"],
    "м": ["м", "метр", "метра", "метров", "мп", "м.п", "пог.м", "пм", "п.м"],
    "км": ["км", "километр", "километра", "километров"],
    "кг": ["кг", "килограмм", "килограмма", "килограммов"],
    "т": ["т", "тонна", "тонны", "тонн"],
    "л": ["л", "литр", "литра", "литров"],
    "бухта": ["бухта", "бухты", "бухт"],
    "рулон": ["рулон", "рулона", "рулонов", "рул"],
    "м2": ["м2", "м²", "кв.м", "кв м", "квм"],
    "см": ["см", "сантиметр", "сантиметра", "сантиметров"],
    # 223-ФЗ: «условная единица» — не штука; нужна сверка с каталогом.
    "усл.ед": [
        "усл.ед",
        "усл. ед",
        "усл ед",
        "условная единица",
        "условные единицы",
        "условных единиц",
        "у.е",
    ],
}

_LOOKUP = {v: canon for canon, variants in _VARIANTS.items() for v in variants}


def units_in(text: str) -> set[str]:
    """Канонические единицы, которые встречаются в тексте отдельными словами."""
    words = re.findall(r"[^\W\d_][\w.²]*(?:\s+ед)?", text.casefold().replace("ё", "е"))
    found = {normalize_unit(w) for w in words}
    found |= {normalize_unit(m) for m in re.findall(r"условн\w*\s+единиц\w*", text.casefold())}
    return {u for u in found if u}


def normalize_unit(raw: str) -> str | None:
    """Каноническая единица или None, если написание незнакомо."""
    key = " ".join(raw.casefold().replace("ё", "е").split()).strip(" .,;:")
    return _LOOKUP.get(key)
