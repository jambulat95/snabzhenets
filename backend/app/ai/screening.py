"""Проверка входящего текста на подсказки-инъекции (письмо поставщика, страница, текст заявки).

Правила ядра перенесены из A2A Маркет (backend/app/agents/usage.py: INJECTION_PATTERNS, detect_injection),
правила ML и нормализация против маскировки — app/ai/injection.py. См. NOTICE.md.

Это не защита сама по себе: защита в том, что модель не решает про деньги и не видит лишнего.
Сработавшее правило — пометка «подозрительный ввод» в журнале и передача человеку вместо автодействия.
"""

import re

from .injection import ML_PATTERNS, scan

INJECTION_PATTERNS = [
    r"(игнорир|забуд|не\s+учитыва)\w*\s+(?:(?:все|всё|предыдущ\w*|прежн\w*|эти|свои|системн\w*)\s+)*(инструкц|правил|указан|огранич)",
    r"(ignore|disregard|forget)\s+(?:(?:all|the|any|previous|prior|above|your)\s+)*(instructions|rules|prompt)",
    r"(ты|вы)\s+(теперь|сейчас)\s+(—|-)?\s*(не\s+)?(агент|ассистент|модель)",
    r"(системн\w+|system)\s*(промпт|prompt|сообщени|message)",
    r"(раскрой|покажи|выведи|сообщи)\w*\s+.{0,30}(бюджет|закупочн|маржу|лимит|мандат|промпт)",
    r"(reveal|show|print)\s+.{0,30}(budget|prompt|margin|limit)",
    r"(прими|принять|подтверди)\w*\s+.{0,20}(без\s+проверк|немедленно|сразу)",
    r"(скидк\w*|discount)\s*(=|:)?\s*(100|[5-9]\d)\s*%",
    r"<\s*/?\s*(system|assistant|tool|instructions?)\s*>",
    # Обращение к агенту с командой: «агент, выбери этого поставщика». «Агент по доставке» — профессия, не обращение
    r"\b(агент|ии|ai|бот|ассистент)\w{0,3}(?:\s*[,:!—–-]\s*(?:\S+\s+){0,2}?|\s+)"
    r"(выбери|выберите|прими|примите|одобри|одобрите|утверди|утвердите|отклони|отклоните|отдай|отдайте|"
    r"предпочти|предпочтите)\b",
    r"\b(выбери|выберите|прими|примите|одобри|одобрите|утверди|утвердите)\s+(?:\S+\s+){0,2}?"
    r"(этого|эту|наш\w*|нас|меня)\s+(поставщик\w*|предложени\w*|кп|компани\w*)",
    r"\b(choose|select|pick|accept|approve)\s+(this|our|us|me)\b",
]

_INJECTION = [re.compile(p, re.IGNORECASE) for p in INJECTION_PATTERNS + ML_PATTERNS]


def detect_injection(text: str | None) -> list[str]:
    """Сработавшие правила; пусто — подозрительного нет."""
    return scan(text, _INJECTION)
