import pytest

from app.agents.ml.gateway.pii import anonymize


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("С уважением, Иванов Пётр, +7 900 123-45-67", "С уважением, [ФИО], [телефон]"),
        ("тел. 8 (495) 123-45-67, моб. 89161234567", "тел. [телефон], моб. [телефон]"),
        ("+79001234567", "[телефон]"),
        ("Пишите на zakupki@gamma-zavod.ru", "Пишите на [email]"),
        ("ИНН 7701234567, КПП 770101001", "ИНН [реквизит], КПП [реквизит]"),
        ("ИНН/КПП 7701234567/770101001", "ИНН/КПП [реквизит]"),
        ("р/с 40702810900000012345 БИК 044525225", "р/с [реквизит] БИК [реквизит]"),
        ("Контактное лицо: Петров И.И.", "Контактное лицо: [ФИО]"),
        ("Руководитель отдела снабжения Сидорова Анна Викторовна",
         "Руководитель отдела снабжения [ФИО]"),
        ("Согласовано: Кузнецов Алексей Игоревич", "Согласовано: [ФИО]"),
        ("С уважением,\nИванов Пётр\n+7 900 123-45-67", "С уважением,\n[ФИО]\n[телефон]"),
    ],
)  # fmt: skip
def test_personal_data_is_masked(text: str, expected: str) -> None:
    assert anonymize(text).text == expected


@pytest.mark.parametrize(
    "text",
    [
        "1) 30784809 - ПОДШИПНИК 6024 C3, 2 Штука.",
        "Пускатель ПМЛ 1501 IP00 110В ВТМ арт. ВТМ00052310 или эквивалент - 10 Штука",
        "89123456789 Болт М12х80 DIN 933 8.8 — 50 шт",  # голые цифры без «+7» и «тел.» — код
        "Кабель ВВГнг-LS 5*2,5 — 100 м",
        "Двигатель АИР 80 В4 1,5 кВт 3000 об/мин — 2 шт",
        "Манжета 1.2-40х62-1 ГОСТ 8752-79 — 50 шт",
        "С уважением, отдел снабжения.",
        "Менеджер по продажам ответит в течение дня",
        "Подшипник 6204-2RS SKF — 10 шт",
        # Ложные срабатывания, найденные на eval: «контакт» внутри слова, перенос через строку
        "Контактор КМЭ 3210 32А 220В - 20 шт",
        "С уважением, отдел снабжения.\nПросим указать срок поставки и наличие.",
        "С уважением, отдел снабжения.\nДоставка до склада покупателя.",
    ],
)
def test_articles_and_ordinary_text_are_untouched(text: str) -> None:
    assert anonymize(text).text == text


def test_line_count_is_preserved_and_counts_reported() -> None:
    text = "1. Подшипник 6205-2RS — 10 шт\n\nС уважением,\nИванов Пётр\n+7 900 123-45-67"
    masked = anonymize(text)
    assert masked.text.count("\n") == text.count("\n")
    assert masked.found["телефон"] == 1 and "6205-2RS" in masked.text


def test_quantities_after_sht_are_not_a_phone() -> None:
    text = "Подшипник 6205 — шт. 1 250 300 1 400"
    assert anonymize(text).text == text
